import Image from "next/image";

/**
 * Знак компании — официальный логотип заказчика, получен 27.08.2026.
 *
 * ── Почему картинкой, а не кодом ─────────────────────────────────
 *
 * До этого знак был нарисован кодом (SVG) — см. `LogoMarkGrid` ниже.
 * Теперь это настоящий логотип компании, и рисовать его заново нельзя.
 *
 * ── Почему только знак, без надписи ──────────────────────────────
 *
 * Присланный логотип — **квадратный**: знак сверху, «AETHER» и
 * «SYSTEM & CO.» под ним. В шапке высота знака 32 точки, и при такой
 * высоте всего логотипа надпись «SYSTEM & CO.» получилась бы около
 * трёх точек — нечитаемая каша. Квадратные логотипы в узкой шапке не
 * работают в принципе.
 *
 * Поэтому из логотипа взят сам знак (буква «A» с росчерком и дроном),
 * а название набрано шрифтом сайта — оно и так подобрано под макет.
 * Полный логотип целиком лежит в `public/logo-full.png` на случай,
 * если понадобится где-то, где есть место.
 *
 * ── Почему светлый ───────────────────────────────────────────────
 *
 * Исходник сделан для светлого фона: средняя яркость 34 из 255. Фон
 * сайта почти чёрный, на нём такой знак тонет. Светлая версия сделана
 * скриптом `scripts/make-logo-light.mjs` (режим `mono`), вариант
 * выбран заказчиком.
 *
 * ⚠️ Это временная мера. Как только заказчик пришлёт **вектор**
 * (.svg/.ai/.eps) и штатную светлую версию — заменить: вектор чёток
 * в любом размере и не весит лишнего.
 */
export function LogoMark({ className = "" }: { className?: string }) {
  return (
    <Image
      src="/logo-mark.png"
      alt=""
      aria-hidden="true"
      /* Размеры исходного файла. Нужны, чтобы место под знак
         резервировалось сразу и страница не дёргалась при загрузке. */
      width={245}
      height={139}
      priority
      className={className}
    />
  );
}

