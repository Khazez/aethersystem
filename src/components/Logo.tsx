/** Знак + название компании. */
export function Logo({ compact = false }: { compact?: boolean }) {
  return (
    <span className="flex items-center gap-3">
      {/* w-auto, а не w-8: знак не квадратный (245×139), и жёсткая
          ширина его бы сплющила. */}
      <LogoMark className="h-8 w-auto shrink-0" />
      <span className="flex flex-col leading-none">
        <span className="text-[0.9375rem] font-semibold tracking-[0.14em] text-ink">
          AETHER
        </span>
        {!compact && (
          <span className="mt-1 font-mono text-[0.5625rem] tracking-[0.28em] text-ink-faint">
            SYSTEM &amp; CO.
          </span>
        )}
      </span>
    </span>
  );
}
