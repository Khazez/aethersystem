/**
 * Решает, показывать ли сцену полёта и в каком качестве.
 *
 * Зачем отдельный файл без импорта three.js: проверка выполняется ДО
 * загрузки трёхмерной библиотеки (см. FlightBackdropLazy). Если бы
 * функции жили внутри сцены, 600 КБ библиотеки уезжали бы на телефон
 * даже там, где сцену решено не показывать.
 *
 * Раньше сцена просто выключалась на экране уже 1024 пикселей — то
 * есть на всех телефонах. Сайт там выглядел мёртвым: статичный текст
 * на тёмном фоне. Теперь сцена работает и на телефоне, но в облегчённом
 * виде: меньше точек на кадр, меньше облаков, без свечения. Отключение
 * осталось только там, где оно оправдано, — при системном «уменьшить
 * движение» и без поддержки трёхмерной графики.
 */

/** Уровень качества сцены. */
export type Quality = "full" | "lite";

/**
 * Настройки, которые отличают телефон от компьютера.
 *
 * Все три величины подобраны замерами: главная цена кадра на телефоне —
 * не геометрия, а число закрашиваемых точек и полупрозрачные облака
 * поверх друг друга.
 */
export type QualityProfile = {
  level: Quality;
  /** Предел плотности точек. У телефона она втрое выше, чем у монитора. */
  maxPixelRatio: number;
  /** Сглаживание краёв. На телефоне вместо него — умеренная плотность. */
  antialias: boolean;
  /** Сколько облачных клубов расставить по коридору. */
  cloudCount: number;
  /** Свечение ярких мест. Самый дорогой из эффектов. */
  bloom: boolean;
};

/** Есть ли рабочий WebGL — технология, которой рисуется трёхмерная графика. */
export function hasWebGL(): boolean {
  try {
    const c = document.createElement("canvas");
    return !!(c.getContext("webgl2") || c.getContext("webgl"));
  } catch {
    return false;
  }
}

/**
 * Экономный режим или заведомо медленная связь.
 *
 * Читается из `navigator.connection` — поле есть не во всех браузерах,
 * поэтому обращение осторожное.
 *
 * При включённой экономии сцена не запускается вовсе, и вместо неё
 * показывается то же содержание обычным списком. Промежуточного
 * варианта — сцена с упрощённым аппаратом вместо настоящего — нет
 * намеренно: он выглядел заметно хуже, а половинчатая экономия
 * (8 МБ материалов всё равно качаются) смысла не имеет.
 */
function isSavingData(): boolean {
  const nav = navigator as Navigator & {
    connection?: { saveData?: boolean; effectiveType?: string };
  };
  const c = nav.connection;
  if (!c) return false;
  if (c.saveData) return true;
  return c.effectiveType === "slow-2g" || c.effectiveType === "2g";
}

/** Слабое устройство: мало памяти или мало вычислительных ядер. */
function isWeakDevice(): boolean {
  const nav = navigator as Navigator & { deviceMemory?: number };
  if (typeof nav.deviceMemory === "number" && nav.deviceMemory <= 4) return true;
  return (navigator.hardwareConcurrency ?? 8) <= 4;
}

/**
 * Показывать ли сцену вообще.
 *
 * «Уменьшить движение» — системная настройка, которую человек включает
 * осознанно: при вестибулярных нарушениях крупное движение на экране
 * вызывает тошноту. Для госзаказа доступность обязательна, поэтому эта
 * настройка перевешивает любые пожелания к красоте.
 */
export function isSceneEnabled(): boolean {
  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    return false;
  }
  /* Экономия трафика — тоже осознанный выбор человека, и весит сцена
     около 8 МБ материалов. Уважаем так же, как «уменьшить движение». */
  if (isSavingData()) return false;
  return hasWebGL();
}

/** Подбирает настройки под устройство. */
export function readQuality(): QualityProfile {
  const narrow = window.matchMedia("(max-width: 1023px)").matches;
  const lite = narrow || isWeakDevice();

  if (!lite) {
    return {
      level: "full",
      maxPixelRatio: 1.6,
      antialias: true,
      cloudCount: 340,
      bloom: true,
    };
  }

  return {
    level: "lite",
    /* 1.25 вместо 1.6. У телефона плотность точек доходит до 3 —
       без предела кадр стоил бы вшестеро дороже, чем на мониторе. */
    maxPixelRatio: 1.25,
    antialias: false,
    /* 110 вместо 340. Облака полупрозрачные и лежат друг на друге,
       поэтому каждая точка экрана закрашивается по многу раз — на
       мобильном видеочипе это самая дорогая часть кадра. */
    cloudCount: 110,
    /* Свечение — отдельные проходы отрисовки в уменьшенные буферы.
       На телефоне отнимает больше, чем добавляет. */
    bloom: false,
  };
}
