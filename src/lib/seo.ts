import type { Metadata } from "next";

import {
  locales,
  localeHtmlLang,
  defaultLocale,
  type Locale,
} from "@/i18n/config";

/**
 * Адреса страниц для поисковых систем.
 *
 * ── Что чинится ──────────────────────────────────────────────────
 *
 * До 27.08.2026 `alternates` задавались в макете `[locale]/layout.tsx`.
 * Макет один на все страницы раздела и своего адреса не знает, поэтому
 * КАЖДАЯ страница объявляла канонической ссылкой главную:
 *
 *     /ru/contacts  →  <link rel="canonical" href="/ru">
 *
 * Каноническая ссылка говорит поисковику: «главный адрес этой страницы
 * — вот такой». Получалось, что все внутренние страницы объявляли себя
 * копиями главной и могли выпасть из выдачи. То же с `hrefLang` —
 * они указывали на главную вместо соответствующей страницы на другом
 * языке.
 *
 * Теперь адрес передаётся явно на каждой странице.
 */

/**
 * Полный адрес сайта.
 *
 * Нужен, потому что канонические ссылки должны быть полными, а не
 * относительными: у сайта два рабочих адреса (собственный домен и
 * технический на vercel.app), и поисковик должен понимать, какой из
 * них главный. Без этого Next.js подставляет адрес конкретной сборки,
 * а он у каждой публикации свой.
 */
export const SITE_URL = "https://aethersystem.kz";

/**
 * Картинка для превью ссылки (1200×630). Показывается, когда адрес
 * сайта вставляют в мессенджер, соцсеть или письмо.
 *
 * Файл рисуется скриптом `scripts/make-og.mjs`, а не на лету: генерация
 * на сервере потребовала бы отдельно подгружать шрифт с кириллицей —
 * лишняя точка отказа ради картинки, которая меняется раз в год.
 */
export const OG_IMAGE = `${SITE_URL}/og.png`;

/**
 * Собирает ссылки на языковые версии одной и той же страницы.
 *
 * @param locale текущий язык
 * @param path   путь внутри языка, без языка и без ведущей косой черты:
 *               "" для главной, "contacts" для /ru/contacts
 */
export function alternates(locale: Locale, path = ""): Metadata["alternates"] {
  const tail = path ? `/${path}` : "";

  return {
    canonical: `/${locale}${tail}`,
    /* hreflang сообщает поисковику, что это одна страница на разных
       языках, а не три разных. Без него версии считаются дублями и
       конкурируют друг с другом. */
    languages: {
      ...Object.fromEntries(
        locales.map((code) => [localeHtmlLang[code], `/${code}${tail}`]),
      ),
      /* x-default — куда вести посетителя, чей язык не совпал ни с одним
         из трёх. Без него поисковик выбирает версию сам и может показать
         казахстанцу английскую страницу. Ведём на язык по умолчанию. */
      "x-default": `/${defaultLocale}${tail}`,
    },
  };
}
