/**
 * `as const` выше фиксирует каждую строку как отдельный тип
 * (например, тип "Главная", а не просто string). Для источника истины
 * это удобно — структура становится точной. Но переводы тогда не
 * подходят по типу: "Home" — это не "Главная".
 *
 * Widen расширяет литеральные типы обратно до string, сохраняя при этом
 * саму структуру объекта. В результате en.ts и kk.ts обязаны повторить
 * все поля и вложенность, но с любым текстом внутри.
 */
type Widen<T> = T extends string
  ? string
  : T extends number
    ? number
    : T extends boolean
      ? boolean
      : T extends readonly (infer U)[]
        ? readonly Widen<U>[]
        : T extends object
          ? { readonly [K in keyof T]: Widen<T[K]> }
          : T;

/** Тип словаря. en.ts и kk.ts обязаны ему соответствовать. */
export type Dictionary = Widen<typeof ru>;
