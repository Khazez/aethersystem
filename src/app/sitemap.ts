import type { MetadataRoute } from "next";

import { SITE_URL } from "@/lib/seo";
import { locales, localeHtmlLang } from "@/i18n/config";

/**
 * Карта сайта — список всех страниц для поисковых систем.
 *
 * Зачем нужна. Робот находит страницы, переходя по ссылкам, и до
 * какой-то может не добраться или добраться нескоро. Карта отдаёт ему
 * весь список сразу. Для сайта на трёх языках это особенно важно:
 * версии на английском и казахском связаны с русской переключателем,
 * и без карты робот может решить, что это второстепенные страницы.
 *
 * Next.js собирает файл из этого кода и отдаёт по `/sitemap.xml`.
 *
 * ⚠️ При добавлении нового раздела не забыть внести его в `PATHS` —
 * иначе он в карту не попадёт. Служебные `/prototype` и `/variants`
 * сюда намеренно не входят: они помечены как не подлежащие
 * индексации.
 */

/** Разделы сайта. Пустая строка — главная. Без языка и без ведущей «/». */
const PATHS = ["", "about", "product", "solutions", "team", "contacts"];

export default function sitemap(): MetadataRoute.Sitemap {
  /* Дата сборки. Точной даты правки каждой страницы у нас нет —
     содержание лежит в словарях, а не в отдельных файлах. Дата сборки
     честнее выдуманной: она показывает, когда сайт последний раз
     обновлялся целиком. */
  const lastModified = new Date();

  return locales.flatMap((locale) =>
    PATHS.map((path) => {
      const tail = path ? `/${path}` : "";

      return {
        url: `${SITE_URL}/${locale}${tail}`,
        lastModified,
        /* Главная важнее внутренних страниц — так робот распределит
           внимание при обходе. */
        priority: path === "" ? 1 : 0.7,
        /* Языковые версии одной страницы, чтобы они не считались
           дублями друг друга. */
        alternates: {
          languages: Object.fromEntries(
            locales.map((code) => [
              localeHtmlLang[code],
              `${SITE_URL}/${code}${tail}`,
            ]),
          ),
        },
      };
    }),
  );
}
