import type { MetadataRoute } from "next";

import { SITE_URL } from "@/lib/seo";

/**
 * `robots.txt` — файл с указаниями поисковым роботам.
 *
 * Робот заходит на сайт и первым делом читает его: что можно обходить,
 * что нельзя и где лежит карта сайта. Файла не было вовсе — роботы
 * обходили сайт наугад и карту не находили.
 *
 * Next.js собирает его из этого кода при сборке и отдаёт по адресу
 * `/robots.txt` — писать текстовый файл руками не нужно.
 *
 * ⚠️ Служебные страницы (`/prototype`, `/variants`) здесь НЕ
 * запрещены, и это намеренно. Они уже помечены в своих метаданных как
 * «не индексировать» (`robots: { index: false }`). Если запретить их
 * ещё и здесь, робот не сможет зайти и прочитать эту пометку — и
 * страница может остаться в выдаче пустой строкой. Запрет в robots.txt
 * и пометка «не индексировать» — взаимоисключающие способы, работает
 * только один за раз.
 */
export default function robots(): MetadataRoute.Robots {
  return {
    rules: {
      userAgent: "*",
      allow: "/",
    },
    sitemap: `${SITE_URL}/sitemap.xml`,
  };
}
